import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdirSync} from 'node:fs';
import {chromium} from 'playwright';

const artifacts='/tmp/lokalblick-issue-check';
mkdirSync(artifacts,{recursive:true});
const server=spawn(process.execPath,['backend/server.mjs'],{env:{...process.env,LOKALBLICK_PORT:'8796'}});
let browser;
const navigate=(page,view)=>page.locator(`.sidebar [data-view="${view}"]`).evaluate(button=>button.click());
const issueId='ACT-DEMO-DAG';
try {
  await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('Server exited '+code)));});
  browser=await chromium.launch({executablePath:process.env.LOKALBLICK_CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://**/*',route=>route.abort());
  await page.goto('http://127.0.0.1:8796/');
  await page.waitForSelector('[data-dashboard-mode]');
  await page.evaluate(async()=>{const {normalize}=await import('/v2/model.js');localStorage.setItem('lokalblick-public-demo-v1',JSON.stringify(normalize(window.LokalblickDemoData)));});
  await page.reload();await page.waitForSelector('[data-dashboard-mode]');
  const saved=()=>page.evaluate(id=>JSON.parse(localStorage.getItem('lokalblick-public-demo-v1')).activities.find(row=>row.id===id),issueId);
  const before=await saved();
  const openIssue=async()=>{
    await navigate(page,'plan');
    await page.locator(`#content [data-edit=activities][data-id="${issueId}"]`).first().click();
    await page.locator('.compact-issue').waitFor();
  };
  await openIssue();
  const form=page.locator('#edit-form');
  assert.equal(await form.locator('.issue-chips [data-issue-chip=status] .issue-field-value').innerText(),'Pågår');
  assert.equal(await form.locator('.issue-chips [data-issue-chip=priority] .issue-field-value').innerText(),'Medel');
  assert.equal(await form.locator('.context-breadcrumb').count(),0,'No duplicate property breadcrumb above the issue name');
  assert.equal(await form.locator('.issue-property-reference [data-context-record=properties]').count(),1);
  assert.equal(await form.locator('.issue-extra').getAttribute('open'),null);
  assert.equal(await form.locator('[name=issueHome]').isVisible(),false);
  assert.equal(await form.locator('[name=type]').isVisible(),false);
  assert.equal(await form.locator('[data-activity-journal-note]').isVisible(),false);
  for(const width of [390,320,667,1440]){
    await page.setViewportSize({width,height:844});
    const order=await form.evaluate(form=>{
      const top=selector=>form.querySelector(selector).getBoundingClientRect().top;
      return ['.issue-heading','.issue-home-row','.issue-description-row','.issue-focus-grid','.issue-focus-timing','.activity-journal','.issue-extra'].map(top);
    });
    assert.ok(order.every((value,index)=>index===0||value>=order[index-1]),'Task-first order at '+width);
    assert.ok(await form.locator('.issue-focus-timing').evaluate(node=>node.getBoundingClientRect().bottom<innerHeight-80),'Cost and timeline are visible without scrolling at '+width);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No overflow at '+width);
    await page.screenshot({path:`${artifacts}/issue-${width}.png`,fullPage:false});
  }
  assert.deepEqual(await saved(),before,'Reading and expanding must never change data');
  await page.setViewportSize({width:390,height:844});
  await form.locator('.issue-note-compose > summary').click();
  await form.locator('[data-activity-journal-note]').fill('Verifierad planlösning från verksamheten.');
  await form.locator('[data-activity-journal-save]').click();
  await page.waitForFunction(()=>document.querySelector('.activity-journal .activity-journal-entries').textContent.includes('Verifierad planlösning'));
  assert.equal(await form.locator('[name=estimatedCostTkr]').count(),1,'Note refresh keeps one cost field');
  assert.equal(await form.locator('[name=startDate]').count(),1,'Note refresh keeps one timeline');
  assert.equal(await form.locator('.activity-journal-history-group').count(),0,'Cost and timeline stay outside notes after refresh');
  assert.equal(await form.locator('.activity-journal-entries > .is-note').count(),1,'Only the latest note is shown initially');
  assert.ok(await form.locator('.issue-older-notes').count());
  assert.deepEqual(await saved(),before,'Saving a note preserves all issue fields');
  await form.locator('[data-editor-activate]').click();
  await form.locator('[name=priority]').selectOption('Hög');
  await form.locator('[name=status]').selectOption('Planerad');
  await form.locator('[name=estimatedCostTkr]').fill('325');
  await form.locator('[name=responsiblePersonId]').selectOption('P2');
  await form.locator('[name=endDate]').fill('2027-06-30');
  await form.locator('[data-issue-save]').click();
  await page.waitForSelector('#edit-form',{state:'detached'});
  const after=await saved();
  assert.equal(after.estimatedCost,325000);assert.equal(after.priority,'Hög');assert.equal(after.status,'Planerad');
  assert.equal(after.responsiblePersonId,'P2');assert.equal(after.endDate,'2027-06-30');
  for(const field of ['title','description','propertyId','objectId','contractId','type','category','includeInBudget'])assert.deepEqual(after[field]??'',before[field]??'','Preserve '+field);
  await openIssue();
  assert.equal(await form.locator('[data-issue-chip=priority]').getAttribute('data-attention'),'high');
  await form.locator('.issue-focus-grid .activity-journal-history > summary').click();
  assert.ok((await form.locator('.issue-focus-grid').innerText()).includes('325 tkr'));
  await page.keyboard.press('Escape');
  // Exercise long text and several append-only notes using synthetic fixtures.
  await page.evaluate(id=>{
    const data=JSON.parse(localStorage.getItem('lokalblick-public-demo-v1'));
    data.activities.find(row=>row.id===id).description='Lång ärendebeskrivning med viktiga förutsättningar. '.repeat(12);
    localStorage.setItem('lokalblick-public-demo-v1',JSON.stringify(data));
  },issueId);
  await page.reload();await page.waitForSelector('[data-dashboard-mode]');await openIssue();
  const expand=form.locator('.issue-description-row [data-issue-expand]');
  assert.equal(await expand.getAttribute('aria-expanded'),'false');
  await expand.click();assert.equal(await expand.getAttribute('aria-expanded'),'true');
  assert.ok(!(await form.locator('#issue-description-text').getAttribute('class')).includes('issue-text-collapsed'));
  await expand.click();
  await form.locator('[data-editor-activate]').click();
  await form.locator('[name=title]').fill('Osparad rubrik');
  page.once('dialog',dialog=>dialog.dismiss());
  await form.locator('[data-editor-close]').click();
  assert.equal(await form.count(),1,'Unsaved changes still require a decision');
  await form.locator('[data-editor-undo]').click();
  assert.equal(await form.locator('#editor-title').innerText(),before.title);
  await page.keyboard.press('Escape');
  await navigate(page,'activities');
  await page.locator(`#content [data-edit=activities][data-id="${issueId}"]`).first().click();
  assert.ok(await page.locator('.compact-issue').count(),'Same layout from the issue list');
  await page.keyboard.press('Escape');
  await page.locator(`#content [data-open-activity-journal="${issueId}"]`).click();
  assert.ok(await form.locator('.issue-note-compose').getAttribute('open')!==null,'Notes shortcut opens the composer');
  await page.keyboard.press('Escape');
  await navigate(page,'plan');
  await page.locator('[data-new-issue]').click();
  assert.ok(await form.locator('.issue-extra').getAttribute('open')!==null,'New cases expose their required type and home');
  await form.locator('[name=title]').fill('Ny kompakt utredning');
  await form.locator('[name=type]').selectOption('Utredning');
  await form.locator('[name=issueHome]').selectOption('property:DEMO-301');
  await form.locator('[name=estimatedCostTkr]').fill('120');
  await form.locator('[name=responsiblePersonId]').selectOption('P1');
  await form.locator('[data-issue-save]').click();
  await page.waitForSelector('#edit-form',{state:'detached'});
  const created=await page.evaluate(()=>JSON.parse(localStorage.getItem('lokalblick-public-demo-v1')).activities.find(row=>row.title==='Ny kompakt utredning'));
  assert.equal(created.estimatedCost,120000);assert.equal(created.type,'Utredning');assert.equal(created.propertyId,'DEMO-301');
  assert.equal(await page.locator('#notice.error').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS: compact task-first order, visible chips, mobile density, one copy of each control, note refresh, history, edit/save, long text, discard protection and shared entry points.');
  console.log('Screenshots: '+artifacts);
} finally {await browser?.close();server.kill();}
